import { randomUUID } from "node:crypto";
import { cp, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { createDatabase } from "@lumolynk/database";
import { sql } from "drizzle-orm";
import { migrate } from "drizzle-orm/node-postgres/migrator";

export async function createTestDatabase(url: string | undefined, throughMigration?: number) {
  if (!url || !new URL(url).pathname.endsWith("_test"))
    throw new Error(
      "TEST_DATABASE_URL must point to a dedicated database ending in _test. See apps/api/.env.example.",
    );
  const admin = createDatabase(url);
  const namespace = `test_${randomUUID().replaceAll("-", "")}`;
  const scopedUrl = new URL(url);
  scopedUrl.searchParams.set("options", `-c search_path=${namespace}`);
  const database = createDatabase(scopedUrl.toString());
  const migrationsDir = await mkdtemp(join(tmpdir(), "lumolynk-migrations-"));
  async function cleanup() {
    await database.pool.end();
    // This namespace is generated by this process; no existing schema is touched.
    await admin.db.execute(sql.raw(`DROP SCHEMA IF EXISTS "${namespace}" CASCADE`));
    await admin.pool.end();
    await rm(migrationsDir, { recursive: true, force: true });
  }
  try {
    await admin.db.execute(sql.raw(`CREATE SCHEMA "${namespace}"`));
    await cp(new URL("../../../../packages/database/migrations", import.meta.url), migrationsDir, {
      recursive: true,
    });
    for (const name of await readdir(migrationsDir)) {
      if (name.endsWith(".sql")) {
        const path = join(migrationsDir, name);
        await writeFile(
          path,
          (await readFile(path, "utf8")).replaceAll('"public".', `"${namespace}".`),
        );
      }
    }
    const journalPath = join(migrationsDir, "meta/_journal.json"),
      journalText = await readFile(journalPath, "utf8");
    if (throughMigration !== undefined) {
      const journal = JSON.parse(journalText) as { entries: { idx: number }[] };
      await writeFile(
        journalPath,
        JSON.stringify({
          ...journal,
          entries: journal.entries.filter((entry) => entry.idx <= throughMigration),
        }),
      );
    }
    const applyMigrations = () =>
      migrate(database.db, { migrationsFolder: migrationsDir, migrationsSchema: namespace });
    await applyMigrations();
    return {
      ...database,
      url: scopedUrl.toString(),
      cleanup,
      migrateRemaining: async () => {
        await writeFile(journalPath, journalText);
        await applyMigrations();
      },
    };
  } catch (error) {
    await cleanup();
    throw error;
  }
}
