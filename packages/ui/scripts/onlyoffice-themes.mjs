// ONLYOFFICE's documented theme-file keys. Keep Lumo's palette in tokens.ts.
// These files require deployment to the document server, including on Docs Cloud.
export function onlyofficeTheme(mode, palette) {
  const colors = {
    "background-normal": palette.surface,
    "background-toolbar": palette.surface,
    "background-toolbar-additional": palette.muted,
    "background-primary-dialog-button": palette.primary,
    "background-accent-button": palette.primary,
    "background-tab-underline": palette.primary,
    "background-notification-popover": palette.elevated,
    "background-notification-badge": palette.primary,
    "background-scrim": "rgba(0, 0, 0, 0.25)",
    "background-loader": palette.background,
    "background-contrast-popover": palette.elevated,
    "highlight-button-hover": palette.muted,
    "highlight-button-pressed": palette.accent,
    "highlight-button-pressed-hover": palette.accent,
    "highlight-primary-dialog-button-hover": palette["primary-hover"],
    "highlight-accent-button-hover": palette["primary-hover"],
    "highlight-accent-button-pressed": palette["primary-hover"],
    "highlight-header-button-hover": palette.muted,
    "highlight-header-button-pressed": palette.accent,
    "highlight-toolbar-tab-underline": palette.primary,
    "highlight-text-select": palette.accent,
    "border-toolbar": palette.border,
    "border-toolbar-active-panel-top": palette.surface,
    "border-divider": palette.border,
    "border-regular-control": palette.input,
    "border-toolbar-button-hover": palette.border,
    "border-preview-hover": palette.primary,
    "border-preview-select": palette.primary,
    "border-control-focus": palette.ring,
    "border-color-shading": palette.border,
    "border-error": palette.destructive,
    "border-contrast-popover": palette.border,
    "border-button-pressed-focus": palette.ring,
    "text-normal": palette.foreground,
    "text-normal-pressed": palette["accent-foreground"],
    "text-secondary": palette["muted-foreground"],
    "text-tertiary": palette["muted-foreground"],
    "text-link": palette.primary,
    "text-link-hover": palette["primary-hover"],
    "text-link-active": palette.primary,
    "text-link-visited": palette.primary,
    "text-inverse": palette["primary-foreground"],
    "text-toolbar-header": palette.foreground,
    "text-contrast-background": palette.foreground,
    "icon-normal": palette["muted-foreground"],
    "icon-normal-pressed": palette["accent-foreground"],
    "icon-inverse": palette["primary-foreground"],
    "icon-toolbar-header": palette["muted-foreground"],
    "icon-notification-badge": palette["primary-foreground"],
    "icon-contrast-popover": palette.foreground,
    "icon-success": palette.success,
    "canvas-background": palette.background,
    // Keep the printed document/page white; interface theming does not restyle its content.
    "canvas-content-background": "#ffffff",
    "canvas-page-border": palette.border,
    "canvas-ruler-background": palette.surface,
    "canvas-ruler-border": palette.border,
    "canvas-ruler-margins-background": palette.muted,
    "canvas-ruler-mark": palette["muted-foreground"],
    "canvas-ruler-handle-border": palette.foreground,
    "canvas-ruler-handle-border-disabled": palette["muted-foreground"],
    "canvas-high-contrast": palette.foreground,
    "canvas-high-contrast-disabled": palette["muted-foreground"],
    "canvas-scroll-thumb": palette.input,
    "canvas-scroll-thumb-hover": palette["muted-foreground"],
    "canvas-scroll-thumb-pressed": palette["muted-foreground"],
    "canvas-scroll-thumb-border": palette.border,
  };
  for (const kind of ["document", "spreadsheet", "presentation", "pdf"]) {
    colors[`toolbar-header-${kind}`] = palette.surface;
    colors[`text-toolbar-header-on-background-${kind}`] = palette.foreground;
  }
  return {
    name: `Lumo ${mode === "dark" ? "Dark" : "Light"}`,
    id: `theme-lumo-${mode}`,
    type: mode,
    colors,
  };
}
